#include "Employee.h"
#include <iostream>
using namespace std;



// Функция, возвращающая объект Employee, созданный с вводом с клавиатуры
employee make_employee()
{
    string name, pos;
    double sal;
    cout << "Введите ФИО: ";
    cin.ignore(); // очистка буфера перед getline
    getline(cin, name);
    cout << "Введите должность: ";
    getline(cin, pos);
    cout << "Введите зарплату: ";
    cin >> sal;

    employee temp(name, pos, sal);  // вызов конструктора с параметрами
    return temp;                    // возврат временного объекта -> копирование
}

// Функция, принимающая объект по значению (вызов конструктора копирования)
void print_employee(employee e)
{
    cout << "Содержимое объекта (печать через функцию print_employee):\n";
    e.show();
}

int main()
{
    setlocale(LC_ALL, "Russian"); // для корректного вывода русских символов

    cout << "=== 1. Конструктор без параметров ===\n";
    employee e1;          // конструктор без параметров
    e1.show();

    cout << "\n=== 2. Конструктор с параметрами ===\n";
    employee e2("Иванов Иван Иванович", "Инженер", 50000.0);
    e2.show();

    cout << "\n=== 3. Конструктор копирования (инициализация e3 = e2) ===\n";
    employee e3 = e2;     // конструктор копирования
    e3.show();

    cout << "\n=== 4. Передача объекта в функцию по значению ===\n";
    print_employee(e3);   // при передаче по значению вызывается конструктор копирования

    cout << "\n=== 5. Возврат объекта из функции и присваивание существующему ===\n";
    // make_employee() создаёт временный объект (конструктор с параметрами),
    // затем при возврате копирует его (конструктор копирования), а потом
    // оператором присваивания (по умолчанию) копирует поля в e1.
    e1 = make_employee();
    cout << "Результат после присваивания:\n";
    e1.show();

    cout << "\n=== Конец программы ===\n";
    return 0;
}